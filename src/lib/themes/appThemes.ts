export function isAppThemeId(value: string | null): value is AppThemeId {
  return value !== null && APP_THEME_IDS.includes(value as AppThemeId);
}

export function applyAppTheme(themeId: AppThemeId, variant: AppThemeVariant) {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;
  const tokens = appThemes[themeId][variant];
  root.dataset.colorTheme = themeId;
  for (const [property, value] of Object.entries(tokens)) {
    root.style.setProperty(property, value);
  }
}

function toGalleryTokens(tokens: ThemeTokens): GalleryThemeTokens {
  const result = {} as GalleryThemeTokens;
  for (const token of THEME_TOKENS) {
    result[token] = tokens[`--${token}`]!;
  }
  return result;
}

function toGalleryTheme(theme: AppTheme): GalleryTheme {
  return {
    id: theme.id,
    name: theme.name,
    description: theme.description,
    light: toGalleryTokens(theme.light),
    dark: toGalleryTokens(theme.dark),
  };
}

